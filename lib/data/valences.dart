/// Alle Wertigkeiten eines Elements.
List<int> valencesOf(int number) => valenceByNumber[number] ?? const [0];

/// Die typische (erste) Wertigkeit eines Elements.
int mainValence(int number) => valencesOf(number).first;

/// Lesbare Darstellung, z. B. "2, 3".
String valenceLabel(int number) => valencesOf(number).join(', ');
